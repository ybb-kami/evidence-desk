const assert = require('node:assert/strict');
const {paper,mermaid} = require('./writing.js');
const id = 'a'.repeat(64), other = 'b'.repeat(64);
const original = 'Literal <img src=x>\n```\nor sample citation [123]';
const hit = {id,name:'local [document] #1.pdf',page:2,block:0,part:1,page_label:'ii',text:original};
const bare = paper('Empty topic');
assert.equal(bare.count,0);
assert.match(bare.markdown,/未选中可核对的本地证据/);
assert.doesNotMatch(bare.markdown,/\/pdf\/|10\.[0-9]{4,}\//);
const anchored = paper('Test <script>\n## injected', [hit,hit,{...hit,part:2},{...hit,id:other}]);
assert.equal(anchored.count,2);
assert.ok(anchored.markdown.startsWith('# Test &lt;script&gt; \\#\\# injected\n'));
assert.ok(anchored.markdown.includes('/pdf/'+id+'#page=2'));
assert.ok(anchored.markdown.includes('页面标签 ii'));
assert.ok(anchored.markdown.includes('````text\n' + original + '\n````'));
assert.equal((anchored.markdown.match(/^- R1/gm)||[]).length,1);
assert.doesNotMatch(anchored.markdown,new RegExp(other));
assert.equal(paper('test',[{...hit,id:'../other'},{...hit,page:0},{...hit,page:651},{...hit,block:-1},{...hit,text:'  '}]).count,0);
assert.equal(paper('test',[hit,{...hit,id:other}]).count,2);
assert.match(paper('test',[hit,{...hit,id:other}]).markdown,/^- R2/m);
assert.match(paper('demo',[hit],'http://127.0.0.1:8766').markdown,/http:\/\/127\.0\.0\.1:8766\/pdf\//);
assert.doesNotMatch(paper('demo',[hit],'https://attacker.example').markdown,/attacker\.example/);
assert.match(mermaid,/^flowchart LR/);
assert.match(mermaid,/逐次同意，仅公开关键词/);
assert.match(mermaid,/User --> CSV/);
assert.doesNotMatch(mermaid,/https?:\/\/|<script|click /);
console.log('Writing scaffold and fixed Mermaid architecture tests passed');

const {methodDiagram} = require('./writing.js');
const method = methodDiagram('文献 → 编码 → 排序\n网络 -> 编码\n编码 → 排序');
assert.equal((method.match(/label=/g) || []).length, 4);
assert.equal((method.match(/ -> /g) || []).length, 3);
assert.ok(method.includes('n3 -> n1;'));
assert.ok(methodDiagram('引用 "A" -> 比较').includes(JSON.stringify('引用 "A"')));
assert.throws(() => methodDiagram('数据 → '));
assert.throws(() => methodDiagram('孤立步骤'));

assert.match(paper('扫描表格识别').markdown, /字符错误率/);
assert.match(paper('检索问答方法').markdown, /检索召回/);
assert.match(paper('比较文本编码器',[hit]).markdown, /相同数据与指标/);
assert.match(paper('比较文本编码器',[hit]).markdown, /逐项对照 E1/);
